#!/usr/bin/env bash
# =====================================================================
# RecapAI — one-command installer for a fresh Ubuntu 22.04/24.04 or Debian 12 VPS behind Cloudflare.
#
#   sudo bash deploy/install.sh myrecap.pinlonmail.com admin@example.com
#
# What it does (safe to re-run):
#   1. Installs Docker + compose plugin, enables swap, sets up the firewall (only SSH + Cloudflare on 80/443)
#   2. Generates .env with strong random secrets (kept if it already exists)
#   3. Checks the Cloudflare Origin Certificate in deploy/certs/
#   4. Builds and starts PostgreSQL, Redis, API, worker, web and Caddy
#   5. Installs a daily off-container database backup cron job
# =====================================================================
set -euo pipefail

DOMAIN="${1:-}"
ADMIN_EMAIL="${2:-}"
APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$APP_DIR"

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m  ✔ %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m  ! %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m  ✘ %s\033[0m\n' "$*"; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root: sudo bash deploy/install.sh <domain> <admin-email>"
[ -n "$DOMAIN" ] || die "Usage: sudo bash deploy/install.sh <domain> <admin-email>"
[ -n "$ADMIN_EMAIL" ] || die "Usage: sudo bash deploy/install.sh <domain> <admin-email>"

COMPOSE="docker compose -f docker-compose.yml -f deploy/docker-compose.cloudflare.yml"

# ---------------------------------------------------------------- 1. system
say "1/6 System packages & Docker"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq ca-certificates curl gnupg ufw openssl cron >/dev/null
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh >/dev/null
fi
systemctl enable --now docker >/dev/null 2>&1 || true
docker compose version >/dev/null 2>&1 || die "docker compose plugin missing (apt-get install docker-compose-plugin)"
ok "Docker $(docker --version | awk '{print $3}' | tr -d ,)"

# Swap: video rendering + Next.js build need memory headroom on small VPSes
if ! swapon --show | grep -q .; then
  MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
  SWAP_GB=$(( MEM_MB < 4096 ? 4 : 2 ))
  fallocate -l "${SWAP_GB}G" /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  ok "Created ${SWAP_GB} GB swap"
fi

# ---------------------------------------------------------------- 2. firewall
say "2/6 Firewall (SSH open, HTTP/HTTPS only from Cloudflare)"
SSH_PORT=$(ss -tlnp 2>/dev/null | awk '/sshd/ {split($4,a,":"); print a[length(a)]; exit}')
SSH_PORT=${SSH_PORT:-22}
ufw --force reset >/dev/null
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow "${SSH_PORT}/tcp" >/dev/null
for ip in $(curl -fsS https://www.cloudflare.com/ips-v4) $(curl -fsS https://www.cloudflare.com/ips-v6); do
  ufw allow proto tcp from "$ip" to any port 80,443 >/dev/null
done
ufw --force enable >/dev/null
ok "ufw enabled (SSH port ${SSH_PORT}; 80/443 from Cloudflare only)"
warn "Docker publishes ports directly; Caddy also rejects any non-Cloudflare request with 403."

# ---------------------------------------------------------------- 3. .env
say "3/6 Configuration (.env)"
rand() { openssl rand -hex "${1:-32}"; }
if [ ! -f .env ]; then
  ADMIN_PASSWORD="$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-16)"
  cat > .env <<ENV
# Generated by deploy/install.sh on $(date -u +%F). Keep this file secret and backed up.
NODE_ENV=production
DOMAIN=${DOMAIN}
WEB_ORIGIN=https://${DOMAIN}
API_PUBLIC_URL=https://${DOMAIN}
SESSION_SECRET=$(rand 32)
SECRETS_KEY=$(rand 32)
SESSION_TTL_DAYS=30
COOKIE_SECURE=true
LOG_LEVEL=info
METRICS_TOKEN=$(rand 16)

POSTGRES_USER=recap
POSTGRES_PASSWORD=$(rand 24)
POSTGRES_DB=recap
REDIS_PASSWORD=$(rand 24)

ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}
SIGNUP_BONUS_CREDITS=30

# Media on this server's disk (Docker volume "media"). Switch to r2 later for unlimited storage.
STORAGE_DRIVER=local
ALLOW_LOCAL_STORAGE_IN_PRODUCTION=true
SIGNED_URL_TTL_SEC=3600
MAX_UPLOAD_MB=2048

# AI keys are added in the website: Admin → AI Models & Keys (Gemini key is enough for Burmese voice).
TTS_PROVIDER=none

WORKER_CONCURRENCY=1
WORKER_CPUS=$(nproc)
WORKER_MEMORY=$(( $(awk '/MemTotal/ {print int($2/1024/1024)}' /proc/meminfo) > 3 ? 3 : 2 ))g
FFMPEG_PRESET=veryfast
FFMPEG_THREADS=0
JOB_TIMEOUT_MIN=60

BACKUP_ENABLED=true
BACKUP_RETENTION_DAYS=14
ENV
  chmod 600 .env
  ok ".env created with random secrets"
  echo "$ADMIN_PASSWORD" > /root/recapai-admin-password.txt && chmod 600 /root/recapai-admin-password.txt
else
  ok ".env exists — keeping it"
  sed -i "s|^DOMAIN=.*|DOMAIN=${DOMAIN}|; s|^WEB_ORIGIN=.*|WEB_ORIGIN=https://${DOMAIN}|; s|^API_PUBLIC_URL=.*|API_PUBLIC_URL=https://${DOMAIN}|" .env
fi

# ---------------------------------------------------------------- 4. origin certificate
say "4/6 Cloudflare Origin Certificate"
mkdir -p deploy/certs
if [ ! -s deploy/certs/origin.pem ] || [ ! -s deploy/certs/origin.key ]; then
  die "Missing deploy/certs/origin.pem and deploy/certs/origin.key.
     Create them in Cloudflare → SSL/TLS → Origin Server → Create Certificate (see DEPLOY.md, step 3), then re-run."
fi
openssl x509 -in deploy/certs/origin.pem -noout >/dev/null 2>&1 || die "deploy/certs/origin.pem is not a valid certificate"
openssl pkey -in deploy/certs/origin.key -noout >/dev/null 2>&1 || die "deploy/certs/origin.key is not a valid private key"
[ "$(openssl x509 -in deploy/certs/origin.pem -noout -pubkey | openssl sha256)" = "$(openssl pkey -in deploy/certs/origin.key -pubout | openssl sha256)" ] \
  || die "origin.pem and origin.key do not match"
chmod 644 deploy/certs/origin.pem; chmod 640 deploy/certs/origin.key
ok "Origin certificate valid until $(openssl x509 -in deploy/certs/origin.pem -noout -enddate | cut -d= -f2)"

# ---------------------------------------------------------------- 5. build & start
say "5/6 Building & starting containers (first build takes 5–15 minutes)"
$COMPOSE build
$COMPOSE up -d
echo -n "  waiting for the API"
for i in $(seq 1 60); do
  if $COMPOSE exec -T api node -e "fetch('http://127.0.0.1:4000/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" >/dev/null 2>&1; then
    echo; ok "API healthy"; break
  fi
  echo -n "."; sleep 5
  [ "$i" = 60 ] && { echo; $COMPOSE logs --tail=80 api; die "API did not become healthy"; }
done
$COMPOSE ps

# ---------------------------------------------------------------- 6. backups
say "6/6 Daily database backup to /var/backups/recapai"
mkdir -p /var/backups/recapai
cat > /etc/cron.d/recapai-backup <<CRON
# RecapAI: nightly pg_dump (keeps 14 days)
30 3 * * * root cd ${APP_DIR} && ${COMPOSE} exec -T postgres sh -c 'pg_dump -U \$POSTGRES_USER \$POSTGRES_DB' | gzip -9 > /var/backups/recapai/recap-\$(date +\%F).sql.gz && find /var/backups/recapai -name '*.sql.gz' -mtime +14 -delete
CRON
ok "Cron installed (/etc/cron.d/recapai-backup)"

echo
printf '\033[1;32m🎉 RecapAI is running at https://%s\033[0m\n' "$DOMAIN"
if [ -f /root/recapai-admin-password.txt ]; then
  echo "   Admin login : ${ADMIN_EMAIL}"
  echo "   Password    : $(cat /root/recapai-admin-password.txt)   (also saved in /root/recapai-admin-password.txt — change it after login)"
fi
echo "   Next: log in → Admin → AI Models & Keys → Add provider key (Google Gemini) → Recommended"
